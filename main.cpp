#include <string>
#include <vector>

void is_prime() {
    int n = 97;
    bool prime = (n > 1);
    for (int d = 2; d * d <= n; ++d) {
        if (n % d == 0) { prime = false; break; }
    }
    (void)prime;
}

void xor_checksum() {
    int values[4] = {12, 7, 25, 40};
    int checksum = 0;
    for (int i = 0; i < 4; ++i) checksum ^= values[i];
    (void)checksum;
}

void shift_left() {
    unsigned int n = 7u;
    unsigned int shifted = n << 4;
    (void)shifted;
}

void pick_max() {
    int a = 17, b = 42, c = 8;
    int m = a;
    if (b > m) m = b;
    if (c > m) m = c;
    (void)m;
}

void vector_reverse() {
    std::vector<int> values;
    values.push_back(1);
    values.push_back(2);
    values.push_back(3);
    std::vector<int> rev;
    for (std::size_t i = values.size(); i > 0; --i) rev.push_back(values[i - 1]);
    (void)rev;
}

void collect_triples() {
    std::vector<int> values;
    for (int i = 1; i <= 5; ++i) values.push_back(i * 3);
    int total = 0;
    for (std::size_t i = 0; i < values.size(); ++i) total += values[i];
    (void)total;
}

extern "C" int sable_thicket();
extern "C" void quiet_haven();
extern "C" void mellow_ember();

int main() {
    is_prime();
    xor_checksum();
    shift_left();
    pick_max();
    vector_reverse();
    collect_triples();
    quiet_haven();
    mellow_ember();
    return sable_thicket();
}
